"""Convert the Phenix-1255 logo into the front panel start screen bitmaps.

Needs Pillow. The generated C file is checked in, so building the firmware
does not need this script; run it only after a logo change:

  python3 tools/logo_to_c.py

The logo PNG must have a transparent background. The lowest band of opaque
rows is the lettering, everything above it the phoenix graphic. Opaque
pixels (any colour) are lit on the display.
"""

import argparse
import pathlib
import sys

try:
    from PIL import Image
except ImportError:
    sys.exit("Pillow is required: apt install python3-pil (Debian/Ubuntu), "
             "brew install pillow (macOS)")

ROOT = pathlib.Path(__file__).resolve().parent.parent
DEFAULT_LOGO = ROOT / "_doc/images/phenix-1255_logo_transparent.png"
DEFAULT_OUT = ROOT / "firmware/src/display/splash_logo.c"

# The phoenix fills the blue zone (pixel rows 16..63), the lettering the
# yellow zone (rows 0..15) with one row margin above and below.
PHOENIX_HEIGHT = 48
TITLE_HEIGHT = 14

# Alpha level (0..255) above which a downscaled pixel is lit; chosen by eye
# so that the gaps between the logo parts stay open.
PHOENIX_THRESHOLD = 120
TITLE_THRESHOLD = 110

HEADER = """\
/*
 * SPDX-License-Identifier: MIT
 * Copyright (c) 2026 Phenix-1255 contributors
 *
 * Generated by tools/logo_to_c.py from
 * {logo}, do not edit.
 */

#include "display/splash_logo.h"
"""


def opaque_bands(alpha):
    """Row ranges [start, end) that contain opaque pixels."""
    width, height = alpha.size
    data = alpha.load()
    bands = []
    start = None
    for y in range(height):
        opaque = any(data[x, y] > 128 for x in range(0, width, 4))
        if opaque and start is None:
            start = y
        elif not opaque and start is not None:
            bands.append((start, y))
            start = None
    if start is not None:
        bands.append((start, height))
    return bands


def crop_rows(alpha, y0, y1):
    part = alpha.crop((0, y0, alpha.width, y1))
    box = part.getbbox()
    return part.crop(box)


def to_bits(alpha, height, threshold):
    width = round(alpha.width * height / alpha.height)
    small = alpha.resize((width, height), Image.LANCZOS)
    data = small.load()
    return [[data[x, y] >= threshold for x in range(width)] for y in range(height)]


def c_bitmap(name, rows):
    width = len(rows[0])
    data = []
    for row in rows:
        for x0 in range(0, width, 8):
            byte = 0
            for i, lit in enumerate(row[x0:x0 + 8]):
                if lit:
                    byte |= 0x80 >> i
            data.append(byte)

    lines = [f"static const uint8_t {name}_bits[] = {{"]
    for i in range(0, len(data), 12):
        lines.append("\t" + ", ".join(f"0x{b:02X}" for b in data[i:i + 12]) + ",")
    lines.append("};")
    lines.append("")
    lines.append(f"const struct fb_bitmap {name} = {{")
    lines.append(f"\t.width = {width},")
    lines.append(f"\t.height = {len(rows)},")
    lines.append(f"\t.bits = {name}_bits,")
    lines.append("};")
    return "\n".join(lines)


def preview(rows):
    return "\n".join("".join("#" if lit else "." for lit in row) for row in rows)


def main():
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--logo", type=pathlib.Path, default=DEFAULT_LOGO)
    parser.add_argument("--out", type=pathlib.Path, default=DEFAULT_OUT)
    parser.add_argument("--preview", action="store_true",
                        help="print the bitmaps instead of writing the C file")
    args = parser.parse_args()

    alpha = Image.open(args.logo).convert("RGBA").getchannel("A")
    bands = opaque_bands(alpha)
    if len(bands) < 2:
        sys.exit(f"{args.logo}: expected the graphic and the lettering as separate bands")

    phoenix = to_bits(crop_rows(alpha, bands[0][0], bands[-2][1]), PHOENIX_HEIGHT,
                      PHOENIX_THRESHOLD)
    title = to_bits(crop_rows(alpha, *bands[-1]), TITLE_HEIGHT, TITLE_THRESHOLD)

    if args.preview:
        print(preview(title))
        print()
        print(preview(phoenix))
        return

    try:
        logo_name = args.logo.resolve().relative_to(ROOT).as_posix()
    except ValueError:
        logo_name = args.logo.name
    text = HEADER.format(logo=logo_name)
    text += "\n" + c_bitmap("splash_phoenix", phoenix) + "\n"
    text += "\n" + c_bitmap("splash_title", title) + "\n"
    args.out.write_text(text)
    print(f"{args.out}: phoenix {len(phoenix[0])}x{len(phoenix)}, "
          f"title {len(title[0])}x{len(title)}")


if __name__ == "__main__":
    main()
